def status_runs(path, offset=2820.0):
    """추적 CSV를 (시작초, 끝초, 상태) 구간 목록으로 묶음"""
    rows = [(float(r["t"]) - offset, r["status"]) for r in csv.DictReader(open(path))]
    runs, start, cur = [], rows[0][0], rows[0][1]
    for (t, st), (t2, _) in zip(rows, rows[1:] + [(rows[-1][0] + 0.033, None)]):
        if st != cur:
            runs.append((start, t, cur))
            start, cur = t, st
    runs.append((start, rows[-1][0] + 0.033, cur))
    return runs


